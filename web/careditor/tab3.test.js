// Differential test for web/careditor/tab3.js (CarMaker.java:2478-2858).
//
// EVERY expected value below is the literal output of web/tools/Tab3Probe.java,
// which drives the REAL CarMaker.run() out of the unpacked java/Game.jar
// through its `if (this.tab == 3)` block, headless, with a recording
// Graphics2D installed as `rd`:
//
//   javac -cp <jar> -d <probe> web/tools/Tab3Probe.java
//   java -Djava.awt.headless=true -Dhttp.proxyHost=127.0.0.1 -Dhttp.proxyPort=1 \
//        --add-opens java.desktop/java.awt=ALL-UNNAMED -cp <probe>:<jar> tools.Tab3Probe
//
// The dead proxy is REQUIRED and is not a convenience: multiplayer.needformadness.com
// still answers in 2026, and without it the real Java takes the network paths
// this chunk drops, so the two sides would describe different worlds (with the
// server live, case C's `++nmc` runs and the row loop then reads a null car
// name). Behind the proxy the Java takes exactly the branches the port
// hard-codes. Three runs of the probe are byte-identical apart from the temp
// directory in loadsounds()'s message, so these numbers are stable.
//
// What is compared is the ORDERED SEQUENCE of Graphics2D calls -- painter's
// algorithm, so order IS the output (TRANSPILE_SPEC §4) -- plus the mutated
// fields. Font metrics differ between Java's rasteriser and any JS one, so
// every stringWidth() the Java asked for was logged WITH its font and its
// answer, and the harness replays exactly those widths; the coordinates then
// compare as exact integers rather than as "close".
//
// NOT COVERED, and it cannot be from here: the three paths that open a
// JOptionPane -- the "N Players" list, the Download confirm, and the X
// remove-from-account confirm. JOptionPane.getRootFrame() throws
// HeadlessException before it ever looks at the message, so the real Java
// cannot be made to produce an expected value for the strings those branches
// build (notably the s2 accumulator with its 17-per-line wrap and its
// ", " / " and " / "\nand " tail). Case G drives the same hit test with the
// button held instead of clicked, which reaches ovbutton's pressed rendering
// without opening a dialog, but the message text itself is unverified.
//
// Real widgets and real sibling chunks throughout -- the Smenu/TextField/
// TextArea from newCarMaker(), and the ported movefield/stringbutton/ovbutton
// that tab3.js imports. A stub that answers only the methods the test author
// noticed is a stub that hides the rest of the call (WORK.md 2026-08-02).

import test from 'node:test';
import assert from 'node:assert/strict';
import { tab3 } from './tab3.js';
import { newCarMaker } from './state.js';

/**
 * Build the CarMaker state, apply a case's setup, run tab3, and return the
 * recorded call log.
 *
 * `probed` is that case's own probe output; its stringWidth lines are the width
 * table, so the JS side measures text exactly as the JVM did.
 */
function run(probed, setup) {
  const widths = new Map();
  for (const line of [...probed.setup, ...probed.calls]) {
    if (!line.startsWith('stringWidth|')) continue;
    const i = line.lastIndexOf('|');
    widths.set(line.slice('stringWidth|'.length, i), Number(line.slice(i + 1)));
  }

  const log = [];
  let recording = false;
  let curFont = { name: 'Dialog', style: 0, size: 12 };
  const esc = (s) => String(s).replace(/\n/g, '\\n');

  // java.awt.FontMetrics is bound to the font the Graphics2D had when
  // getFontMetrics() was called, NOT to whatever it has later -- which matters,
  // because stringbutton()/ovbutton() reassign cm.ftm in the middle of a row
  // and the code after them keeps using it.
  const metricsFor = (f) => ({
    stringWidth(s) {
      const key = `${f.name},${f.style},${f.size}|${esc(s)}`;
      if (!widths.has(key)) throw new Error('no probed width for ' + key);
      const w = widths.get(key);
      if (recording) log.push(`stringWidth|${key}|${w}`);
      return w;
    },
    getHeight() {
      throw new Error('getHeight() was never probed; add it to Tab3Probe first');
    },
  });

  const rd = {
    setColor(r, g, b) { if (recording) log.push(`setColor|${r},${g},${b}`); },
    setFont(f) { curFont = f; if (recording) log.push(`setFont|${f.name},${f.style},${f.size}`); },
    getFontMetrics() { if (recording) log.push('getFontMetrics'); return metricsFor(curFont); },
    drawString(s, x, y) { if (recording) log.push(`drawString|${esc(s)}|${x}|${y}`); },
    drawLine(x1, y1, x2, y2) { if (recording) log.push(`drawLine|${x1}|${y1}|${x2}|${y2}`); },
    drawRect(x, y, w, h) { if (recording) log.push(`drawRect|${x}|${y}|${w}|${h}`); },
    fillRect(x, y, w, h) { if (recording) log.push(`fillRect|${x}|${y}|${w}|${h}`); },
    drawImage(img, x, y) { if (recording) log.push(`drawImage|${x}|${y}`); },
    fillPolygon(xs, ys, n) { if (recording) log.push(`fillPolygon|${n}`); },
    setComposite(a) { if (recording) log.push(`setComposite|${a}`); },
  };

  const cm = newCarMaker();
  cm.rd = rd;
  // Applet + JOptionPane, the pieces the shell supplies. repaint() produced no
  // Graphics2D call in the probe (the Applet has no peer), so it is counted
  // rather than logged; showConfirmDialog is not reached by these cases.
  cm.repaints = 0;
  cm.cursors = [];
  cm.repaint = () => { ++cm.repaints; };
  cm.setCursor = (c) => { cm.cursors.push(c.type); };
  cm.showMessageDialog = () => { if (recording) log.push('showMessageDialog'); };
  cm.showConfirmDialog = () => 0;

  cm.tab = 3;
  cm.tabed = 3;
  setup(cm);
  recording = true;
  tab3(cm);
  recording = false;
  return { cm, log };
}

function check(probed, setup) {
  const { cm, log } = run(probed, setup);
  for (let i = 0; i < Math.max(log.length, probed.calls.length); i++) {
    // deepEqual over 500 strings prints an unreadable wall; name the first
    // divergence, then still assert the whole sequence.
    assert.equal(log[i], probed.calls[i], `call ${i} differs`);
  }
  assert.deepEqual(log, probed.calls);
  assert.equal(`logged=${cm.logged} nmc=${cm.nmc} roto=${cm.roto} btn=${cm.btn}`, probed.fields);
  return cm;
}

